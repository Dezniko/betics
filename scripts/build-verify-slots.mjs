// Builds frontend/public/verify-slots.mjs: a standalone Node verifier for Gods of Power rounds that
// embeds the engine and the published maths, so it runs from any folder with no packages.
//   node scripts/build-verify-slots.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { SLOT_MATH } from '../backend/src/games/slotsMath.js';

const engine = readFileSync(new URL('../backend/src/games/slots.js', import.meta.url), 'utf8');
const math = JSON.stringify(SLOT_MATH);
const out = `// Standalone Node.js verifier for Gods of Power (qu-BETICS slot). No packages, no network, no eval.
// Usage: node verify-slots.mjs round-proof.json
// Recomputes every reel stop, every win and the total payout from the revealed seed, and checks the
// seed opens the lock shown before the bet. Generated by scripts/build-verify-slots.mjs; do not edit by hand.
import { createHash, createHmac } from 'node:crypto';
import { readFileSync, realpathSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const MATH = ${math};

${engine.replace(/^\/\/.*\n/gm, '')}

export function uint32At(serverSeed, clientSeed, nonce) {
  return (draw, counter) => createHmac('sha256', serverSeed).update(\`\${clientSeed}:\${nonce}:slots:\${draw}:\${counter}\`).digest().readUInt32BE(0);
}

export function verifyProof(proof) {
  const problems = [];
  const f = proof.fairness || {};
  if (typeof f.serverSeed !== 'string' || typeof f.serverSeedHash !== 'string') return { ok: false, problems: ['The proof has no revealed seed.'] };
  if (createHash('sha256').update(f.serverSeed).digest('hex') !== f.serverSeedHash) problems.push('The revealed seed does not open the lock.');
  if (proof.expected && proof.expected.serverSeedHash !== f.serverSeedHash) problems.push('The lock differs from the one saved before the bet.');
  let round = null;
  try { round = playRound({ stake: proof.stake, uint32At: uint32At(f.serverSeed, f.clientSeed, f.nonce), math: MATH }); }
  catch (e) { problems.push('The round could not be recomputed: ' + e.message); }
  if (round) {
    const spins = Array.isArray(proof.spins) ? proof.spins : [];
    if (round.spins.length !== spins.length) problems.push(\`\${spins.length} spins recorded, \${round.spins.length} from the seed.\`);
    round.spins.forEach((s, i) => {
      const d = spins[i]; if (!d) return;
      if (JSON.stringify(s.stops) !== JSON.stringify(d.stops)) problems.push(\`Spin \${i + 1}: reel stops differ.\`);
      if (s.winUnits !== d.winUnits) problems.push(\`Spin \${i + 1}: win differs (\${d.winUnits} recorded, \${s.winUnits} from the seed).\`);
    });
    if (round.totalPayoutUnits !== proof.totalPayoutCents) problems.push(\`Total payout differs (\${proof.totalPayoutCents} recorded, \${round.totalPayoutUnits} from the seed).\`);
    if (Number.isSafeInteger(proof.balanceBeforeCents) && Number.isSafeInteger(proof.balanceAfterCents)
      && proof.balanceAfterCents !== proof.balanceBeforeCents - proof.stake + proof.totalPayoutCents) problems.push('The balance after the round does not add up.');
  }
  return { ok: problems.length === 0, problems, round };
}

function main() {
  const file = process.argv[2];
  if (!file) { console.error('Usage: node verify-slots.mjs round-proof.json'); process.exit(2); }
  const proof = JSON.parse(readFileSync(file, 'utf8'));
  const r = verifyProof(proof);
  if (r.ok) { console.log(\`OK: \${r.round.spins.length} spin(s), total payout \${r.round.totalPayoutUnits} units, lock opened by the revealed seed.\`); process.exit(0); }
  console.log('MISMATCH'); for (const p of r.problems) console.log(' - ' + p); process.exit(1);
}
try { if (realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) main(); } catch { /* imported as a module */ }
`;
writeFileSync(new URL('../frontend/public/verify-slots.mjs', import.meta.url), out);
console.log('wrote frontend/public/verify-slots.mjs');
